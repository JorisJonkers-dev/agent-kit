"""Commits and pull requests carry human authorship only.

Two guards, both set up by the workstation setup script. Every Claude profile
turns off Claude Code's own commit trailer and PR line. A git hook,
installer/git-hooks/no-agent-attribution, refuses any commit message that
credits a coding agent and any push that would publish one, whichever agent
or person wrote it. The hook is wired as git config hooks so a repository's
own hooks keep running.

The hook tests drive a real git against a scratch repository. The setup tests
run the checked-in setup script against a temp HOME (tests/setup_harness.py),
with ``git config`` reaching a real git so they read the file the run leaves.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

KIT_ROOT = Path(__file__).resolve().parent.parent
HOOK = KIT_ROOT / "installer" / "git-hooks" / "no-agent-attribution"
sys.path.insert(0, str(Path(__file__).resolve().parent))

from setup_harness import Run, setup_run  # noqa: E402

REAL_GIT = shutil.which("git") or "git"
pytestmark = pytest.mark.skipif(shutil.which("git") is None, reason="needs a real git")

TRAILER = "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"


def _git(repo: Path, *args: str, check: bool = True, stdin: str | None = None) -> subprocess.CompletedProcess[str]:
    env = {**os.environ, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1"}
    return subprocess.run(
        [
            REAL_GIT,
            "-C",
            str(repo),
            "-c",
            "user.name=Owner",
            "-c",
            "user.email=owner@example.invalid",
            "-c",
            "commit.gpgsign=false",
            *args,
        ],
        capture_output=True,
        text=True,
        check=check,
        env=env,
        input=stdin,
    )


def _repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q")
    _git(repo, "config", "hook.guard.command", f'"{HOOK}" commit-msg')
    _git(repo, "config", "hook.guard.event", "commit-msg")
    return repo


def _commit(repo: Path, *paragraphs: str) -> subprocess.CompletedProcess[str]:
    args = ["commit", "-q", "--allow-empty"]
    for paragraph in paragraphs:
        args += ["-m", paragraph]
    return _git(repo, *args, check=False)


@pytest.mark.parametrize(
    "mark",
    [
        TRAILER,
        "co-authored-by: Codex <codex@openai.com>",
        "Co-authored-by: Copilot <copilot@github.com>",
        "\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)",
        "Generated by Cursor",
    ],
)
def test_the_hook_refuses_a_commit_message_that_credits_an_agent(tmp_path: Path, mark: str) -> None:
    result = _commit(_repo(tmp_path), "fix: a change", mark)
    assert result.returncode != 0
    assert "credits a coding agent" in result.stderr


def test_the_hook_accepts_a_commit_with_a_human_co_author(tmp_path: Path) -> None:
    result = _commit(_repo(tmp_path), "fix: a change", "Co-Authored-By: A Person <person@example.invalid>")
    assert result.returncode == 0, result.stderr


def test_the_hook_ignores_attribution_in_comment_lines_git_strips(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    message = tmp_path / "message"
    message.write_text(f"fix: a change\n\n# {TRAILER}\n")
    result = _git(repo, "commit", "-q", "--allow-empty", "--cleanup=strip", "-F", str(message), check=False)
    assert result.returncode == 0, result.stderr


def test_the_hook_runs_next_to_the_repository_s_own_commit_msg_hook(tmp_path: Path) -> None:
    repo = _repo(tmp_path)
    own = repo / ".git" / "hooks" / "commit-msg"
    own.write_text(f'#!/bin/sh\ntouch "{tmp_path / "own-hook-ran"}"\n')
    own.chmod(0o755)
    assert _commit(repo, "fix: a change").returncode == 0
    assert (tmp_path / "own-hook-ran").exists()


def test_the_pre_push_hook_refuses_to_publish_a_commit_that_credits_an_agent(tmp_path: Path) -> None:
    remote = tmp_path / "remote.git"
    _git(tmp_path, "init", "-q", "--bare", str(remote))
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "remote", "add", "origin", str(remote))
    _git(repo, "config", "hook.guard.command", f'"{HOOK}" pre-push')
    _git(repo, "config", "hook.guard.event", "pre-push")
    # --no-verify skips commit-msg, the way an agent would get past it.
    _git(repo, "commit", "-q", "--allow-empty", "--no-verify", "-m", "fix: a change", "-m", TRAILER)
    result = _git(repo, "push", "-q", "origin", "main", check=False)
    assert result.returncode != 0
    assert "would publish commits that credit a coding agent" in result.stderr


def test_the_pre_push_hook_lets_a_clean_branch_through(tmp_path: Path) -> None:
    remote = tmp_path / "remote.git"
    _git(tmp_path, "init", "-q", "--bare", str(remote))
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "remote", "add", "origin", str(remote))
    _git(repo, "config", "hook.guard.command", f'"{HOOK}" pre-push')
    _git(repo, "config", "hook.guard.event", "pre-push")
    _git(repo, "commit", "-q", "--allow-empty", "-m", "fix: a change")
    result = _git(repo, "push", "-q", "origin", "main", check=False)
    assert result.returncode == 0, result.stderr


def _git_stub(calls: Path) -> str:
    # `git config` is real so the run edits the temp HOME's file; everything
    # else stays a recorded no-op, as in the other setup tests.
    return f'if [ "$1" = config ]; then exec "{REAL_GIT}" "$@"; fi\necho "git $*" >> "{calls}"'


def _setup(tmp_path: Path, *, args: tuple[str, ...] = ()) -> Run:
    def prepare(home: Path) -> None:
        settings = home / ".claude" / "settings.json"
        settings.parent.mkdir(parents=True, exist_ok=True)
        settings.write_text(json.dumps({"model": "opus", "attribution": {"commit": "Co-Authored-By: x"}}) + "\n")

    return setup_run(
        tmp_path, "Linux", args=args, prepare_home=prepare, stubs={"git": _git_stub(tmp_path / "calls.log")}
    )


def _global_git(home: Path, key: str) -> str:
    return subprocess.run(
        [REAL_GIT, "config", "--file", str(home / ".gitconfig"), "--get", key],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()


def test_setup_turns_off_claude_code_s_commit_and_pr_attribution_and_keeps_other_settings(tmp_path: Path) -> None:
    run = _setup(tmp_path)
    settings = json.loads((run.home / ".claude" / "settings.json").read_text())
    assert settings["attribution"] == {"commit": "", "pr": ""}
    assert settings["includeCoAuthoredBy"] is False
    assert settings["model"] == "opus"


def test_setup_installs_the_hook_and_registers_it_for_commit_msg_and_pre_push(tmp_path: Path) -> None:
    run = _setup(tmp_path)
    dest = run.home / ".config" / "agent-kit" / "git-hooks" / "no-agent-attribution"
    assert dest.read_bytes() == HOOK.read_bytes()
    assert os.access(dest, os.X_OK)
    for event in ("commit-msg", "pre-push"):
        assert _global_git(run.home, f"hook.agent-kit-no-attribution-{event}.event") == event
        assert _global_git(run.home, f"hook.agent-kit-no-attribution-{event}.command") == f'"{dest}" {event}'


def test_setup_check_mode_changes_nothing(tmp_path: Path) -> None:
    run = _setup(tmp_path, args=("--check",))
    settings = json.loads((run.home / ".claude" / "settings.json").read_text())
    assert settings["attribution"] == {"commit": "Co-Authored-By: x"}
    assert not (run.home / ".config" / "agent-kit" / "git-hooks").exists()
    assert _global_git(run.home, "hook.agent-kit-no-attribution-commit-msg.command") == ""
