"""Commits and pull requests carry the owner's identity only.

The owner's decision: a commit may name only the owner, or a GitHub App bot
that is not an AI agent, as its author, committer or co-author. Every AI agent
and model provider is refused. Setup enforces it three ways:

- each agent with a setting for its own attribution has it turned off (Claude
  Code's settings, Mistral Vibe's ``include_commit_signature``);
- each agent's global instruction file carries the rule as a marked block;
- a git hook, installer/git-hooks/no-agent-attribution, refuses a commit
  message, and a push, that breaks the allowlist kept as data in
  installer/git-hooks/allowed-identities. It is wired as git config hooks so a
  repository's own hooks keep running.

The hook tests drive a real git against a scratch repository. The setup tests
run the checked-in setup script against a temp HOME (tests/setup_harness.py),
with ``git config`` reaching a real git so they read the file the run leaves.
"""

