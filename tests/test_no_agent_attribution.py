# --- pre-push --------------------------------------------------------------


def _pushing_repo(tmp_path: Path) -> tuple[Path, Path]:
    remote = tmp_path / "remote.git"
    _git(tmp_path, "init", "-q", "--bare", str(remote))
    repo = _repo(tmp_path, "pre-push")
    _git(repo, "remote", "add", "origin", str(remote))
    return repo, remote


def _push(repo: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return _git(repo, "push", "-q", *args, "origin", "main", check=False)


def test_the_pre_push_hook_refuses_a_commit_whose_message_credits_an_agent(tmp_path: Path) -> None:
    repo, _ = _pushing_repo(tmp_path)
    # Only the pre-push hook is wired here, the way an agent gets past
    # commit-msg with --no-verify.
    _commit(repo, "fix: a change", "\n".join(VIBE_LINES))
    result = _push(repo)
    assert result.returncode != 0
    assert "would publish commits that credit someone other than the owner" in result.stderr
    assert VIBE_LINES[1] in result.stderr


def test_the_pre_push_hook_refuses_an_agent_author(tmp_path: Path) -> None:
    repo, _ = _pushing_repo(tmp_path)
    _commit(repo, "fix: a change", who=("Claude Opus 5 (1M context)", "noreply@anthropic.com"), committer=OWNER)
    result = _push(repo)
    assert result.returncode != 0
    assert "author: Claude Opus 5 (1M context) <noreply@anthropic.com>" in result.stderr
    assert "committer:" not in result.stderr


def test_the_pre_push_hook_refuses_an_agent_committer(tmp_path: Path) -> None:
    repo, _ = _pushing_repo(tmp_path)
    _commit(repo, "fix: a change", committer=("Mistral Vibe", "vibe@mistral.ai"))
    result = _push(repo)
    assert result.returncode != 0
    assert "committer: Mistral Vibe <vibe@mistral.ai>" in result.stderr


