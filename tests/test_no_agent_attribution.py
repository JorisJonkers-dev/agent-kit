def _git(
    repo: Path,
    *args: str,
    check: bool = True,
    who: tuple[str, str] = OWNER,
    committer: tuple[str, str] | None = None,
    env: dict[str, str] | None = None,
) -> subprocess.CompletedProcess[str]:
    committer = committer or who
    run_env = {
        **os.environ,
        "GIT_CONFIG_GLOBAL": os.devnull,
        "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_AUTHOR_NAME": who[0],
        "GIT_AUTHOR_EMAIL": who[1],
        "GIT_COMMITTER_NAME": committer[0],
        "GIT_COMMITTER_EMAIL": committer[1],
        **(env or {}),
    }
    return subprocess.run(
        [REAL_GIT, "-C", str(repo), "-c", "commit.gpgsign=false", *args],
        capture_output=True,
        text=True,
        check=check,
        env=run_env,
    )


def _repo(tmp_path: Path, event: str = "commit-msg") -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "config", "hook.guard.command", f'"{HOOK}" {event}')
    _git(repo, "config", "hook.guard.event", event)
    return repo


def _commit(
    repo: Path,
    *paragraphs: str,
    who: tuple[str, str] = OWNER,
    committer: tuple[str, str] | None = None,
    env: dict[str, str] | None = None,
) -> subprocess.CompletedProcess[str]:
    args = ["commit", "-q", "--allow-empty"]
    for paragraph in paragraphs:
        args += ["-m", paragraph]
    return _git(repo, *args, check=False, who=who, committer=committer, env=env)


