def _git_stub(calls: Path) -> str:
    # `git config` is real so the run edits the temp HOME's file; everything
    # else stays a recorded no-op, as in the other setup tests.
    return f'if [ "$1" = config ]; then exec "{REAL_GIT}" "$@"; fi\necho "git $*" >> "{calls}"'


def _setup(root: Path, *, args: tuple[str, ...] = (), platform: str = "Linux") -> Run:
    def prepare(home: Path) -> None:
        settings = home / ".claude" / "settings.json"
        settings.parent.mkdir(parents=True, exist_ok=True)
        settings.write_text(json.dumps({"model": "opus", "attribution": {"commit": "Co-Authored-By: x"}}) + "\n")
        mine = home / ".codex" / "AGENTS.md"
        mine.parent.mkdir(parents=True, exist_ok=True)
        mine.write_text("# My own Codex notes\n")

    return setup_run(root, platform, args=args, prepare_home=prepare, stubs={"git": _git_stub(root / "calls.log")})


@pytest.fixture(scope="module")
def fresh(tmp_path_factory: pytest.TempPathFactory) -> Run:
    return _setup(tmp_path_factory.mktemp("attribution-fresh"), platform="Darwin")


def _global_git(home: Path, key: str) -> str:
    return subprocess.run(
        [REAL_GIT, "config", "--file", str(home / ".gitconfig"), "--get", key],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()


