def test_the_graph_is_a_finite_dag_so_the_attempt_cap_is_never_reached(
    workflow: dict[str, Any],
    nodes: list[dict[str, Any]],
    edges: list[dict[str, Any]],
) -> None:
    """No cycle, so no edge runs twice and one attempt per edge is enough."""
    ids = [node["id"] for node in nodes]
    assert len(ids) == len(set(ids))
    out: dict[str, list[str]] = {i: [] for i in ids}
    for edge in edges:
        assert edge["from"] in out
        assert edge["to"] == "$end" or edge["to"] in out, edge
        if edge["to"] != "$end":
            out[edge["from"]].append(edge["to"])

    state: dict[str, int] = {}

    def visit(node_id: str) -> None:
        assert state.get(node_id) != 1, f"cycle through {node_id}"
        if state.get(node_id) == 2:
            return
        state[node_id] = 1
        for target in out[node_id]:
            visit(target)
        state[node_id] = 2

    visit(workflow["entry"])
    assert set(state) == set(ids), "every node is reachable from the entry"
    assert workflow["control"]["max_attempts"] >= 1
    assert all(edge["to"] != "$new-round" for edge in edges)
    pairs = [(edge["from"], edge["to"], edge["on"]) for edge in edges]
    assert len(pairs) == len(set(pairs))
