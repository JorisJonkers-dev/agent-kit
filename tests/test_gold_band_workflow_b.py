def test_the_gates_are_pairs_of_a_wrapper_and_a_copier_in_four_rounds(
    nodes: list[dict[str, Any]],
    edges: list[dict[str, Any]],
) -> None:
    ids = [node["id"] for node in nodes]
    for suffix in ROUNDS:
        chain = [f"{kind}-{gate}{suffix}" for gate in GATES for kind in ("gate", "copy")]
        for index in range(len(chain) - 1):
            assert _out(edges, chain[index])["success"] == chain[index + 1]
        for name in chain:
            node = _node(nodes, name)
            assert node["provider"] == name
            assert node["success_condition"] == {"path": "$.exit_code", "equals": 0}
        for gate in GATES:
            assert ids.index(f"copy-{gate}{suffix}") == ids.index(f"gate-{gate}{suffix}") + 1


def test_a_failed_gate_goes_to_a_repair_and_a_failed_copier_still_ends_the_run(
    edges: list[dict[str, Any]],
) -> None:
    """A gate has a failure edge into the next repair; a copier (a report that does not verify) has none."""
    targets = {"": "repair-1", "-r1": "repair-2", "-r2": "gates-escalation", "-r3": "final-check"}
    for suffix, target in targets.items():
        for gate in GATES:
            assert _out(edges, f"gate-{gate}{suffix}")["failure"] == target
            assert "failure" not in _out(edges, f"copy-{gate}{suffix}")
    for n in SLICES:
        assert "failure" not in _out(edges, f"gate-findings-{n}")
        assert "failure" not in _out(edges, f"copy-findings-{n}")


def test_every_repair_is_followed_by_all_the_gates_and_fresh_critics_before_any_exit(
    nodes: list[dict[str, Any]],
    edges: list[dict[str, Any]],
) -> None:
    """repair-N reruns the gates, and no path from a repair reaches the end without a code-review record."""
    assert [n["id"] for n in nodes if n["id"].startswith("repair-")] == ["repair-1", "repair-2"]
    for repair in REPAIRS:
        assert _out(edges, f"repair-{repair}") == {"success": f"gate-build-r{repair}"}
        assert not _reaches(edges, f"repair-{repair}", "$end", RECORDS)
        goal = _node(nodes, f"repair-{repair}")["goal"]
        assert "never edit or delete a test" in goal and "fresh critics" in goal
    # The second failed repair judges and pauses, then the review still runs.
    assert _out(edges, "gates-escalation") == {"success": "gates-check", "failure": "gates-check"}
    assert _out(edges, "gates-check") == {"success": "self-review"}
    assert _out(edges, "final-check") == {"success": "$end"}
    for suffix in ROUNDS[:3]:
        assert _out(edges, f"copy-coverage{suffix}") == {"success": "self-review"}


def test_the_repairs_are_the_writer_s_family(nodes: list[dict[str, Any]]) -> None:
    writer = _node(nodes, "writer-s1")
    for name in ("repair-1", "repair-2", "self-review"):
        node = _node(nodes, name)
        assert (node["provider"], node["model"]) == (writer["provider"], writer["model"])


