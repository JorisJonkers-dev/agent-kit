#: The slices the file unrolls, which is also the cap per ticket.
SLICES = [1, 2, 3]

#: The gate rounds: the first pass, after each of the two repairs, and the final pass after the review.
ROUNDS = ["", "-r1", "-r2", "-r3"]
GATES = ["build", "test", "lint", "coverage"]
REPAIRS = [1, 2]

#: The family the personal instance may not bind at all.
