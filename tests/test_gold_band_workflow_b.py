"""Workflow B v2 as a Gold Band workflow template (issues #448, #451, #797).

The template at ``installer/gold-band/workflows/workflow-b.json`` is the Gold
Band shape of Workflow B for the personal instance. v2 replaces "all tests
first" with unrolled TDD slices:

* a plan node (the test author) reads the spec's Testing Decisions, the test
  seams, and plans at most three vertical slices;
* per slice, the test author writes ONE failing test, a test critic of a third
  family looks for implementation-coupled and tautological tests (the finding
  check keeps only findings with a checkable quote) and, when it finds any, the
  test author revises once; then the writer makes that one test green;
* after the last slice build, tests, lint and coverage run through the gate
  shim and a failing gate goes to a repair node of the writer (never ends the
  run), twice at most, with the Opus escalation and a manual check after that;
* the writer's own review and then the runner's ``ticket-review`` stage,
  generated by ``critique-block`` (read-only tripwire, quote check, refute
  round), review the change on the Standards and Spec axes with critics from
  competitor families, accept it, or send it back to the writer once and
  review it again with fresh critics, then the Opus escalation and a manual
  check.

These tests read the template as a file and need no Gold Band binary or Rust
toolchain (the workflow lint and the generated block are proved by the
``workflow-lint`` and ``critique-block`` crates, the headless proof by the
``gold-band-proof`` crate, docs/gold-band-proof.md).
"""

