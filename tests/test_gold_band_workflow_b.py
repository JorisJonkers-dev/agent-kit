#: The Opus nodes: the gate escalation and the code review's, each ending in -escalation.
ESCALATIONS = ["gates-escalation", "ticket-review-escalation"]

#: The code review's record nodes, which every path from a writing node to the end must cross.
RECORDS = {"gate-critique-ticket-review-record", "gate-critique-ticket-review-record-2"}


