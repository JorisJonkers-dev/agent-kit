def test_the_code_review_is_the_runner_s_ticket_review_stage_after_the_writer_s_self_review(
    nodes: list[dict[str, Any]],
    edges: list[dict[str, Any]],
) -> None:
    ids = {node["id"] for node in nodes}
    for step in ("prepare", "fan-out", "refute", "record"):
        assert f"gate-critique-ticket-review-{step}" in ids
        assert f"gate-critique-ticket-review-{step}-2" in ids
    assert _out(edges, "self-review")["success"] == "gate-critique-ticket-review-prepare"
    assert "does not block" in _node(nodes, "self-review")["goal"]
    # An accepted round goes to the final gates; round 1 failing goes to the writer, round 2 failing to the escalation.
    assert _out(edges, "accept-ticket-review-1") == {"success": "gate-build-r3", "failure": "ticket-review-revise-1"}
    assert _out(edges, "accept-ticket-review-2") == {"success": "gate-build-r3", "failure": "ticket-review-escalation"}
    assert _out(edges, "ticket-review-revise-1") == {"success": "gate-critique-ticket-review-prepare-2"}
    # The orchestrator is bound to the writer's family, so the runner leaves that family out of the roster.
    orchestrator = _node(nodes, "ticket-review-verdicts")
    assert _family(orchestrator["model"]) == _family(_node(nodes, "writer-s1")["model"])
    assert "deep depth" in _node(nodes, "gate-critique-ticket-review-fan-out")["goal"]


