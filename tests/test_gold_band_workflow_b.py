def _family(model: str) -> str:
    """The model family a model id names, with any LiteLLM route prefix dropped."""
    name = model.rsplit("/", 1)[-1]
    for family in ("mistral", "deepseek", "glm", "sonnet", "opus", "gemini"):
        if family in name:
            return "anthropic" if family in ("sonnet", "opus") else family
    raise AssertionError(f"no known family in {model}")


def _node(nodes: list[dict[str, Any]], node_id: str) -> dict[str, Any]:
    return next(node for node in nodes if node["id"] == node_id)


def _out(edges: list[dict[str, Any]], node_id: str) -> dict[str, str]:
    """The targets of a node's edges, by the outcome they follow."""
    return {edge["on"]: edge["to"] for edge in edges if edge["from"] == node_id}


def _reaches(edges: list[dict[str, Any]], start: str, goal: str, avoid: set[str]) -> bool:
    """Whether ``goal`` can be reached from ``start`` without entering a node of ``avoid``."""
    seen: set[str] = set()
    todo = [start]
    while todo:
        current = todo.pop()
        if current == goal:
            return True
        if current in seen or current in avoid:
            continue
        seen.add(current)
        todo.extend(edge["to"] for edge in edges if edge["from"] == current)
    return False


