def test_the_spec_s_test_seams_reach_the_plan_and_every_test_author_node(
    nodes: list[dict[str, Any]],
) -> None:
    """The plan and every test author node are told to read the Testing Decisions seams."""
    plan = _node(nodes, "slice-plan")
    assert "Testing Decisions" in plan["goal"] and "seams" in plan["goal"]
    for n in SLICES:
        goal = _node(nodes, f"test-author-s{n}")["goal"]
        assert "seam" in goal and "Testing Decisions" in goal
        assert "slice-plan.json" in goal


def test_there_are_exactly_three_slices_and_no_all_tests_first_node(
    nodes: list[dict[str, Any]],
) -> None:
    """The slices are bounded at three and no node writes every test up front."""
    ids = [node["id"] for node in nodes]
    assert [i for i in ids if i.startswith("test-author-s")] == [f"test-author-s{n}" for n in SLICES]
    assert [i for i in ids if i.startswith("writer-s")] == [f"writer-s{n}" for n in SLICES]
    assert "tests-written" not in {node.get("output", {}).get("artifact") for node in nodes}
    assert "writer" not in ids and "test-author" not in ids
    assert "at most 3" in _node(nodes, "slice-plan")["goal"]


def test_each_slice_writes_one_test_then_the_critic_then_the_writer_makes_it_green(
    nodes: list[dict[str, Any]],
    edges: list[dict[str, Any]],
) -> None:
    """test-author-sN, test-critic-N, the finding check, verdict-N, writer-sN, then the next slice."""
    previous = "slice-plan"
    for n in SLICES:
        chain = [f"test-author-s{n}", f"test-critic-{n}", f"gate-findings-{n}", f"copy-findings-{n}", f"verdict-{n}"]
        assert _out(edges, previous)["success"] == chain[0]
        for index in range(len(chain) - 1):
            assert _out(edges, chain[index]) == {"success": chain[index + 1]}
        assert _out(edges, f"verdict-{n}") == {"success": f"writer-s{n}", "failure": f"test-revise-{n}"}
        assert _out(edges, f"test-revise-{n}") == {"success": f"writer-s{n}"}
        previous = f"writer-s{n}"
        assert "ONE failing test" in _node(nodes, f"test-author-s{n}")["goal"]
        goal = _node(nodes, previous)["goal"]
        assert "fail (red)" in goal and "pass (green)" in goal and "never edit or delete a test" in goal
    assert _out(edges, "writer-s3") == {"success": "gate-build"}


def test_the_critic_runs_on_a_slice_s_test_before_its_writer_starts(
    edges: list[dict[str, Any]],
) -> None:
    """Every way into a slice's writer crosses that slice's test critic."""
    for n in SLICES:
        assert not _reaches(edges, "slice-plan", f"writer-s{n}", {f"test-critic-{n}"})
        assert _reaches(edges, "slice-plan", f"writer-s{n}", set())


