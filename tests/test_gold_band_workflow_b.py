def test_every_writing_node_reaches_the_end_only_through_a_review_record(
    edges: list[dict[str, Any]],
    nodes: list[dict[str, Any]],
) -> None:
    """From every node that writes tests or code, the end is reached only after a code-review record."""
    writing = [
        node["id"]
        for node in nodes
        if node.get("output", {}).get("artifact", "").endswith(("-written", "-implementation"))
    ]
    # The tests, the test revisions and the code of three slices, the two repairs and the self-review.
    assert len(writing) == 3 * 3 + 2 + 1
    for node_id in writing:
        assert not _reaches(edges, node_id, "$end", RECORDS), node_id


