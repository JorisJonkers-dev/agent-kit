#!/usr/bin/env python3
"""Turn off Mistral Vibe's commit signature in one Vibe home's config.

Vibe adds a section to its system prompt that tells the model to end every
commit with "Generated by Mistral Vibe." and a ``Co-Authored-By: Mistral Vibe``
trailer. Its config key ``include_commit_signature`` (default true) decides
whether that section is sent. Commits carry the owner's identity only, so this
sets the key to false and keeps every other setting and comment. The file is
read back, so the caller can trust the value rather than the exit code.

Usage::

    uv run --no-project --with tomlkit python scripts/vibe-no-commit-signature.py --config <config.toml>
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import tomlkit

KEY = "include_commit_signature"


def turn_off(config: Path) -> int:
    text = config.read_text() if config.is_file() else ""
    doc = tomlkit.parse(text)
    if KEY in doc:
        doc[KEY] = False
        text = tomlkit.dumps(doc)
    else:
        # A top-level key must come before the first table, or TOML reads it
        # as part of that table, so it goes first.
        text = f"{KEY} = false\n" + (f"\n{text}" if text.strip() else "")
    config.parent.mkdir(parents=True, exist_ok=True)
    config.write_text(text)
    if tomlkit.parse(config.read_text()).get(KEY) is not False:
        print(f"vibe-no-commit-signature: FAILED, {KEY} is not false in {config}", file=sys.stderr)
        return 1
    print(f"vibe-no-commit-signature: {KEY} = false in {config}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Turn off Mistral Vibe's commit signature")
    parser.add_argument("--config", type=Path, required=True)
    return turn_off(parser.parse_args(argv).config)


if __name__ == "__main__":
    raise SystemExit(main())
