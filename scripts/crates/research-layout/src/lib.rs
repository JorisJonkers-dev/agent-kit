    struct FakeOutside {
        config: Result<String, String>,
        visibility: Result<String, String>,
        add: Result<String, String>,
        calls: Vec<String>,
    }

    impl FakeOutside {
        fn fresh() -> Self {
            Self {
                config: Err("code 1".to_string()),
                visibility: Ok("private".to_string()),
                add: Ok(String::new()),
                calls: Vec::new(),
            }
        }
    }

    impl Outside for FakeOutside {
        fn visibility(&mut self, _url: &str) -> Result<String, String> {
            self.calls.push("visibility".to_string());
            self.visibility.clone()
        }

        fn git(&mut self, repo: &Path, args: &[&str]) -> Result<String, String> {
            self.calls
                .push(format!("git {} {}", repo.display(), args.join(" ")));
            if args.first() == Some(&"config") {
                return self.config.clone();
            }
            self.add.clone()
        }
    }

