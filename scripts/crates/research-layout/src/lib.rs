//! Keeps a papers directory honest (issue #356).
//!
//! The directory holds `catalog.json` (one object per paper), a theme folder
//! per entry with a hand-written `README.md` and a generated `INDEX.md`,
//! `notes/` with front matter citing catalog ids, and the generated top
//! `INDEX.md`. Three commands:
//!
//! * `research-layout check <PAPERS_DIR>` names one path and one rule per
//!   problem line on stderr and exits 1;
//! * `research-layout index <PAPERS_DIR>` regenerates every `INDEX.md`,
//!   deterministically, so a second run changes nothing;
//! * `research-layout mount <REPO_ROOT> <REMOTE_URL>` adds the papers
//!   repository as a submodule at `research/`, idempotently, refusing a
//!   public or non-GitHub remote.
//!
//! Exit codes: 0 success, 1 a rule failed, 2 bad usage. Success prints to
//! stdout, problems to stderr as `research-layout: <path>: <rule>`.

use std::collections::{BTreeMap, BTreeSet};
use std::ffi::OsString;
use std::fs;
use std::path::Path;
use std::process::Command;

use serde::Deserialize;
use serde_json::Value;

pub const NAME: &str = env!("CARGO_PKG_NAME");

/// First line of every generated INDEX.md.
const MARKER: &str = "<!-- generated by research-layout index; do not edit -->";
/// Top-level names the layout allows next to the catalog's theme groups.
const TOP: [&str; 6] = [
    "README.md",
    "INDEX.md",
    "catalog.json",
    "themes.md",
    "notes",
    "evaluations",
];
const TIERS: [&str; 4] = ["A", "B", "C", "D"];
const CONFIG_ARGS: [&str; 5] = [
    "config",
    "-f",
    ".gitmodules",
    "--get",
    "submodule.research.url",
];

type Rule = &'static str;
const BAD_CATALOG: Rule = "bad-catalog";
const BAD_TIER: Rule = "bad-tier";
const INDEX_STALE: Rule = "index-stale";
const LISTED_FILE_MISSING: Rule = "listed-file-missing";
const MISSING_EXPLAINER: Rule = "missing-explainer";
const MISSING_FIELD: Rule = "missing-field";
const NO_FOLDER: Rule = "no-theme-folder";
const QUOTE_NOT_FOUND: Rule = "quote-not-found";
const TIER_BELOW_MIN: Rule = "tier-below-min";
const UNEXPECTED_TOP: Rule = "unexpected-toplevel";
const UNKNOWN_CITE: Rule = "unknown-cite";
const UNLISTED_FILE: Rule = "unlisted-file";
const WRITE_FAILED: Rule = "write-failed";

/// One problem: the path it names and the rule that path broke.
pub type Problem = (String, String);

fn problem(path: &str, rule: Rule) -> Problem {
    (path.to_string(), rule.to_string())
}

#[derive(Deserialize)]
struct Quote {
    text: String,
    page: String,
}

#[derive(Deserialize)]
struct Entry {
    id: String,
    title: String,
    theme: String,
    tier: String,
    files: Vec<String>,
    year: Option<i64>,
    summary: Option<String>,
    #[serde(default)]
    quotes: Vec<Quote>,
}

/// Runs of whitespace collapse to one space before quote comparison.
fn collapse(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn tier_rank(tier: &str) -> Option<u8> {
    TIERS.iter().position(|t| *t == tier).map(|i| i as u8)
}

fn read_values(dir: &Path) -> Result<Vec<Value>, Problem> {
    let text = match fs::read_to_string(dir.join("catalog.json")) {
        Ok(t) => t,
        Err(_) => return Err(problem("catalog.json", BAD_CATALOG)),
    };
    match serde_json::from_str(&text) {
        Ok(v) => Ok(v),
        Err(_) => Err(problem("catalog.json", BAD_CATALOG)),
    }
}

/// Parses each catalog entry on its own, so one broken entry is one problem
/// instead of a dead whole-file read.
fn parse_entries(values: &[Value]) -> (Vec<Entry>, Vec<Problem>) {
    let mut entries = Vec::new();
    let mut problems = Vec::new();
    for (i, v) in values.iter().enumerate() {
        match serde_json::from_value::<Entry>(v.clone()) {
            Ok(e) => {
                if !TIERS.contains(&e.tier.as_str()) {
                    problems.push(problem(&format!("catalog.json#{}", e.id), BAD_TIER));
                }
                entries.push(e);
            }
            Err(_) => {
                let id = v
                    .get("id")
                    .and_then(Value::as_str)
                    .map(str::to_string)
                    .unwrap_or_else(|| format!("p{i}"));
                problems.push(problem(&format!("catalog.json#{id}"), MISSING_FIELD));
            }
        }
    }
    (entries, problems)
}

fn by_theme<'a>(entries: &'a [Entry]) -> BTreeMap<&'a str, Vec<&'a Entry>> {
    let mut groups: BTreeMap<&str, Vec<&Entry>> = BTreeMap::new();
    for e in entries {
        groups.entry(e.theme.as_str()).or_default().push(e);
    }
    groups
}

fn meta(e: &Entry) -> String {
    match e.year {
        Some(y) => format!("({y}, {})", e.tier),
        None => format!("({})", e.tier),
    }
}

/// The top-level INDEX.md: every theme with its entry count, then every
/// entry with title, year, tier and a link to its theme.
fn top_index(entries: &[Entry]) -> String {
    let mut out = format!("{MARKER}\n# Papers\n\n");
    if entries.is_empty() {
        out.push_str("No entries yet.\n");
        return out;
    }
    out.push_str("## Themes\n\n");
    for (theme, group) in by_theme(entries) {
        out.push_str(&format!("- [{theme}]({theme}/INDEX.md) ({} entries)\n", group.len()));
    }
    out.push_str("\n## Entries\n\n");
    let mut sorted: Vec<&Entry> = entries.iter().collect();
    sorted.sort_by(|a, b| (&a.theme, &a.title).cmp(&(&b.theme, &b.title)));
    for e in sorted {
        out.push_str(&format!(
            "- **{}** {} [{theme}]({theme}/INDEX.md)\n",
            e.title,
            meta(e),
            theme = e.theme
        ));
    }
    out
}

/// One theme's INDEX.md: its entries sorted by year then title, with the
/// summary when present.
fn theme_index(theme: &str, group: &[&Entry]) -> String {
    let mut out = format!("{MARKER}\n# {theme} ({} entries)\n\n", group.len());
    let mut sorted: Vec<&Entry> = group.to_vec();
    sorted.sort_by(|a, b| (a.year, &a.title).cmp(&(b.year, &b.title)));
    for e in sorted {
        let summary = match &e.summary {
            Some(s) => format!(": {s}"),
            None => String::new(),
        };
        out.push_str(&format!("- **{}** {}{summary}\n", e.title, meta(e)));
    }
    out
}

fn write_index(dir: &Path, rel: &str, want: &str, problems: &mut Vec<Problem>) {
    if fs::write(dir.join(rel), want).is_err() {
        problems.push(problem(rel, WRITE_FAILED));
    }
}

/// Rewrites every INDEX.md from the entries, creating theme folders.
fn regenerate(dir: &Path, entries: &[Entry]) -> Vec<Problem> {
    let mut problems = Vec::new();
    write_index(dir, "INDEX.md", &top_index(entries), &mut problems);
    for (theme, group) in by_theme(entries) {
        if fs::create_dir_all(dir.join(theme)).is_err() {
            problems.push(problem(theme, NO_FOLDER));
            continue;
        }
        let rel = format!("{}/INDEX.md", theme);
        write_index(dir, &rel, &theme_index(theme, &group), &mut problems);
    }
    problems
}

/// Every rule violation `check` reports, in a stable order.
pub fn check(dir: &Path) -> Vec<Problem> {
    let values = match read_values(dir) {
        Ok(v) => v,
        Err(p) => return vec![p],
    };
    let (entries, mut problems) = parse_entries(&values);
    problems.extend(unexpected(dir, &entries));
    problems.extend(theme_problems(dir, &entries));
    problems.extend(missing_problems(dir, &entries));
    problems.extend(index_problems(dir, &entries));
    problems.extend(note_problems(dir, &entries));
    problems.extend(quote_problems(dir, &entries));
    problems
}

/// A top-level file or folder must be a catalog theme group or a known name.
fn unexpected(dir: &Path, entries: &[Entry]) -> Vec<Problem> {
    let groups: BTreeSet<&str> = entries
        .iter()
        .filter_map(|e| e.theme.split('/').next())
        .collect();
    let mut names: Vec<String> = fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| !TOP.contains(&n.as_str()) && !groups.contains(n.as_str()))
        .collect();
    names.sort();
    names.iter().map(|n| problem(n, UNEXPECTED_TOP)).collect()
}

/// Collects every file under `dir` as a path relative to `base`.
fn walk(dir: &Path, base: &Path, out: &mut Vec<String>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for e in entries.flatten() {
        let path = e.path();
        if path.is_dir() {
            walk(&path, base, out);
        } else if let Ok(rel) = path.strip_prefix(base) {
            out.push(rel.to_string_lossy().replace('\\', "/"));
        }
    }
}

/// A theme file is allowed when a catalog entry lists it or it sits in the
/// `<name>-images/` folder of a listed file.
fn allowed_file(listed: &[String], file: &str) -> bool {
    if listed.iter().any(|f| f.as_str() == file) {
        return true;
    }
    listed.iter().any(|f| {
        let path = Path::new(f.as_str());
        let Some(stem) = path.file_stem() else {
            return false;
        };
        let folder = path.parent().unwrap_or_else(|| Path::new(""));
        let images = folder.join(format!("{}-images", stem.to_string_lossy()));
        Path::new(file).starts_with(images)
    })
}

fn theme_problems(dir: &Path, entries: &[Entry]) -> Vec<Problem> {
    let mut problems = Vec::new();
    for (theme, group) in by_theme(entries) {
        if !dir.join(theme).join("README.md").is_file() {
            problems.push(problem(theme, MISSING_EXPLAINER));
        }
        let listed: Vec<String> = group.iter().flat_map(|e| e.files.iter().cloned()).collect();
        let mut found = Vec::new();
        walk(&dir.join(theme), dir, &mut found);
        found.sort();
        for f in found {
            let known = f == format!("{theme}/README.md")
                || f == format!("{theme}/INDEX.md")
                || allowed_file(&listed, &f);
            if !known {
                problems.push(problem(&f, UNLISTED_FILE));
            }
        }
    }
    problems
}

fn missing_problems(dir: &Path, entries: &[Entry]) -> Vec<Problem> {
    let mut problems = Vec::new();
    for e in entries {
        for f in &e.files {
            if !dir.join(f).is_file() {
                problems.push(problem(f, LISTED_FILE_MISSING));
            }
        }
    }
    problems
}

fn stale(dir: &Path, rel: &str, want: &str) -> bool {
    !fs::read_to_string(dir.join(rel)).is_ok_and(|t| t == want)
}

fn index_problems(dir: &Path, entries: &[Entry]) -> Vec<Problem> {
    let mut problems = Vec::new();
    if stale(dir, "INDEX.md", &top_index(entries)) {
        problems.push(problem("INDEX.md", INDEX_STALE));
    }
    for (theme, group) in by_theme(entries) {
        let rel = format!("{theme}/INDEX.md");
        if stale(dir, &rel, &theme_index(theme, &group)) {
            problems.push(problem(&rel, INDEX_STALE));
        }
    }
    problems
}

/// Front matter between `---` lines and the body after it.
fn front_matter(text: &str) -> (Vec<&str>, Vec<&str>) {
    let all: Vec<&str> = text.lines().collect();
    if all.is_empty() || all[0] != "---" {
        return (Vec::new(), all);
    }
    match all.iter().skip(1).position(|l| *l == "---") {
        Some(i) => (all[1..i + 1].to_vec(), all[i + 2..].to_vec()),
        None => (Vec::new(), all),
    }
}

fn min_tier(fm: &[&str]) -> &str {
    fm.iter()
        .find_map(|l| l.strip_prefix("min_tier:"))
        .map(str::trim)
        .unwrap_or("B")
}

fn cites(fm: &[&str]) -> Vec<String> {
    let mut out = Vec::new();
    for l in fm {
        if let Some(list) = l.strip_prefix("cites:").map(str::trim) {
            let list = list.trim_start_matches('[').trim_end_matches(']');
            for id in list.split(',') {
                let id = id.trim();
                if !id.is_empty() {
                    out.push(id.to_string());
                }
            }
        }
    }
    out
}

/// Body quotes: a `> text` block-quote line followed by `-- <page path>`.
fn quotes(body: &[&str]) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for (i, l) in body.iter().enumerate() {
        let Some(text) = l.strip_prefix('>') else {
            continue;
        };
        let Some(next) = body.get(i + 1) else {
            continue;
        };
        let Some(page) = next.strip_prefix("-- ") else {
            continue;
        };
        out.push((text.trim().to_string(), page.trim().to_string()));
    }
    out
}

/// A quote holds when its page exists and its text, whitespace-collapsed, is
/// a substring of the page's collapsed text.
fn quote_ok(dir: &Path, quote: &str, page: &str) -> bool {
    match fs::read_to_string(dir.join(page)) {
        Ok(stored) => collapse(&stored).contains(&collapse(quote)),
        Err(_) => false,
    }
}

fn note_names(dir: &Path) -> Vec<String> {
    let mut names: Vec<String> = fs::read_dir(dir.join("notes"))
        .into_iter()
        .flatten()
        .flatten()
        .filter(|e| {
            e.file_name().to_string_lossy() != "README.md"
                && e.path().extension().is_some_and(|x| x == "md")
        })
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .collect();
    names.sort();
    names
}

fn note_problems(dir: &Path, entries: &[Entry]) -> Vec<Problem> {
    let tiers: BTreeMap<&str, &str> = entries
        .iter()
        .map(|e| (e.id.as_str(), e.tier.as_str()))
        .collect();
    let mut problems = Vec::new();
    for name in note_names(dir) {
        let rel = format!("notes/{name}");
        let text = fs::read_to_string(dir.join(&rel)).unwrap_or_default();
        let (fm, body) = front_matter(&text);
        let min = tier_rank(min_tier(&fm)).unwrap_or(1);
        for id in cites(&fm) {
            match tiers.get(id.as_str()) {
                None => problems.push(problem(&rel, UNKNOWN_CITE)),
                Some(tier) => match tier_rank(tier) {
                    Some(rank) if rank > min => problems.push(problem(&rel, TIER_BELOW_MIN)),
                    _ => {}
                },
            }
        }
        for (quote, page) in quotes(&body) {
            if !quote_ok(dir, &quote, &page) {
                problems.push(problem(&page, QUOTE_NOT_FOUND));
            }
        }
    }
    problems
}

fn quote_problems(dir: &Path, entries: &[Entry]) -> Vec<Problem> {
    let mut problems = Vec::new();
    for e in entries {
        for q in &e.quotes {
            if !quote_ok(dir, &q.text, &q.page) {
                problems.push(problem(&q.page, QUOTE_NOT_FOUND));
            }
        }
    }
    problems
}

/// The two outside effects of `mount`, behind a trait so the tests use a
/// fake: GitHub's answer about the remote and a run of git.
pub trait Outside {
    /// Returns the visibility gh reports for `owner/name`.
    fn visibility(&mut self, url: &str) -> Result<String, String>;
    /// Runs `git -C <repo> <args>` and returns its output.
    fn git(&mut self, repo: &Path, args: &[&str]) -> Result<String, String>;
}

/// `owner/name` from an https or ssh GitHub URL, or a refusal.
fn owner_name(url: &str) -> Result<String, String> {
    let trimmed = url.trim().trim_end_matches(".git").trim_end_matches('/');
    const FORMS: [&str; 3] = [
        "https://github.com/",
        "git@github.com:",
        "ssh://git@github.com/",
    ];
    for form in FORMS {
        if let Some(rest) = trimmed.strip_prefix(form) {
            let parts: Vec<&str> = rest.split('/').filter(|p| !p.is_empty()).collect();
            if parts.len() == 2 {
                return Ok(parts.join("/"));
            }
        }
    }
    Err(format!("{url}: not a GitHub URL"))
}

fn do_mount(outside: &mut dyn Outside, repo: &Path, url: &str) -> (String, i32) {
    let owner = match owner_name(url) {
        Ok(o) => o,
        Err(m) => return (format!("{m}, cannot verify visibility"), 1),
    };
    let mounted = outside.git(repo, &CONFIG_ARGS).ok().and_then(|set| owner_name(&set).ok());
    if mounted.as_deref() == Some(owner.as_str()) {
        return ("research/ already mounted".to_string(), 0);
    }
    let visibility = match outside.visibility(&owner) {
        Ok(v) => v,
        Err(e) => return (format!("{url}: cannot check visibility: {e}"), 1),
    };
    if visibility.trim().eq_ignore_ascii_case("public") {
        return (format!("{url}: remote is public"), 1);
    }
    match outside.git(repo, &["submodule", "add", url, "research"]) {
        Ok(_) => ("research/ mounted".to_string(), 0),
        Err(e) => (format!("research/: {e}"), 1),
    }
}

// The one piece the task allows to go untested: this real impl only spawns
// the two outside processes; every decision around it is tested against the
// fake Outside above.
fn spawn(program: &str, args: &[&str]) -> Result<String, String> {
    let out = Command::new(program)
        .args(args)
        .output()
        .map_err(|e| e.to_string())?;
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).trim().into_owned())
    } else {
        Err(String::from_utf8_lossy(&out.stderr).trim().into_owned())
    }
}

pub struct RealOutside;

impl Outside for RealOutside {
    fn visibility(&mut self, url: &str) -> Result<String, String> {
        spawn("gh", &["repo", "view", url, "--json", "visibility", "--jq", ".visibility"])
    }

    fn git(&mut self, repo: &Path, args: &[&str]) -> Result<String, String> {
        let repo = repo.to_string_lossy().into_owned();
        let mut argv = vec!["-C"];
        argv.push(repo.as_str());
        argv.extend(args.iter().copied());
        spawn("git", &argv)
    }
}

fn line(path: &str, rule: &str) -> String {
    format!("{NAME}: {path}: {rule}")
}

fn problems_out(problems: &[Problem]) -> i32 {
    for (path, rule) in problems {
        eprintln!("{}", line(path, rule));
    }
    1
}

fn usage() -> String {
    format!(
        "usage: {NAME} check <PAPERS_DIR>\n       {NAME} index <PAPERS_DIR>\n       {NAME} mount <REPO_ROOT> <REMOTE_URL>"
    )
}

fn check_cmd(dir: &Path) -> i32 {
    let problems = check(dir);
    if problems.is_empty() {
        println!("{NAME}: ok");
        0
    } else {
        problems_out(&problems)
    }
}

fn index_cmd(dir: &Path) -> i32 {
    let values = match read_values(dir) {
        Ok(v) => v,
        Err(p) => {
            eprintln!("{}", line(&p.0, &p.1));
            return 1;
        }
    };
    let (entries, entry_problems) = parse_entries(&values);
    if !entry_problems.is_empty() {
        return problems_out(&entry_problems);
    }
    let problems = regenerate(dir, &entries);
    if problems.is_empty() {
        println!("{NAME}: index written");
        0
    } else {
        problems_out(&problems)
    }
}

fn mount_cmd(outside: &mut dyn Outside, repo: &str, url: &str) -> i32 {
    let (message, code) = do_mount(outside, Path::new(repo), url);
    if code == 0 {
        println!("{NAME}: {message}");
    } else {
        eprintln!("{NAME}: {message}");
    }
    code
}

/// Runs one command line and returns its exit code: 0 success, 1 a rule
/// failed, 2 bad usage. Success prints to stdout, problems to stderr.
pub fn run<I>(args: I, outside: &mut dyn Outside) -> i32
where
    I: IntoIterator<Item = OsString>,
{
    let words: Vec<String> = args
        .into_iter()
        .map(|a| a.to_string_lossy().into_owned())
        .collect();
    match words.as_slice() {
        [cmd, dir] if cmd == "check" => check_cmd(Path::new(dir.as_str())),
        [cmd, dir] if cmd == "index" => index_cmd(Path::new(dir.as_str())),
        [cmd, repo, url] if cmd == "mount" => mount_cmd(outside, repo.as_str(), url.as_str()),
        _ => {
            eprintln!("{}", usage());
            2
        }
    }
}

