//! Validates and re-indexes the papers directory behind the agent-kit
//! research crate, and mounts the papers repository behind it (#356).
//!
//! A papers directory holds `catalog.json` (an array of entries with `id`,
//! `title`, `theme`, `tier` A-D, `files`, and optional `year`, `summary`,
//! `abstract`, `quotes`), a folder per named theme holding a hand-written
//! `README.md` (the explainer) and a generated `INDEX.md`, a generated
//! top-level `INDEX.md`, and `notes/` whose Markdown files cite catalog ids
//! under a front-matter `min_tier` and quote stored pages.
//!
//! `check <PAPERS_DIR>` fails, each problem one line on stderr as
//! `research-layout: <path>: <rule>`, for:
//! * a file under a theme folder no catalog entry lists (`unlisted-file`;
//!   the explainer `README.md`, `INDEX.md` and `<name>-images/` folders of a
//!   listed file are allowed);
//! * a listed file that does not exist (`file-not-found`);
//! * a theme folder without `README.md` (`missing-theme-readme`);
//! * an `INDEX.md` that differs from what `index` generates (`stale-index`);
//! * a top-level file or folder that is neither a theme group used by the
//!   catalog nor one of the allowed names (`not-allowed`);
//! * a catalog entry with a missing field (`missing-field`) or a tier
//!   outside A-D (`bad-tier`);
//! * a note citing an id not in the catalog (`unknown-cite`);
//! * a note citing an entry whose tier is worse than the note's `min_tier`
//!   (`tier-below-min`);
//! * a quote whose text, whitespace collapsed, is not a substring of its
//!   stored page, or whose page does not exist (`quote-not-found`).
//!
//! `index <PAPERS_DIR>` regenerates every `INDEX.md` deterministically;
//! `mount <REPO_ROOT> <REMOTE_URL>` adds the papers repository as a git
//! submodule at `research/`, refusing a public or unverifiable remote.
//!
//! Exit codes: 0 ok, 1 a rule failed, 2 bad usage. Problems go to stderr,
//! success to stdout.

use serde::Deserialize;
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::ffi::{OsStr, OsString};
use std::fs;
use std::path::{Component, Path};

pub const NAME: &str = env!("CARGO_PKG_NAME");

/// The first line of every generated `INDEX.md`.
const MARKER: &str = "<!-- generated by research-layout index; do not edit -->";
const CATALOG: &str = "catalog.json";
const TIERS: [&str; 4] = ["A", "B", "C", "D"];
const ALLOWED_FILES: [&str; 4] = ["README.md", "INDEX.md", "catalog.json", "themes.md"];
const ALLOWED_DIRS: [&str; 2] = ["notes", "evaluations"];

/// One quote of a stored fetched page (an entry's `quotes` items).
#[derive(Deserialize)]
struct Quote {
    text: String,
    page: String,
}

/// One `catalog.json` entry; `abstract` and other unknown fields are allowed
/// and ignored. The required fields report as `missing-field` when absent.
#[derive(Deserialize)]
struct Entry {
    id: String,
    title: String,
    theme: String,
    tier: String,
    files: Vec<String>,
    year: Option<i64>,
    summary: Option<String>,
    quotes: Option<Vec<Quote>>,
}

/// Collapses every run of whitespace to one space.
fn collapse(text: &str) -> String {
    let mut out = String::new();
    for word in text.split_whitespace() {
        if !out.is_empty() {
            out.push(' ');
        }
        out.push_str(word);
    }
    out
}

/// The `quote-not-found` problem for one quote, or `None` when the stored
/// page exists and carries the quote's text (whitespace collapsed).
fn quote_problem(papers: &Path, text: &str, page: &str) -> Option<String> {
    if escapes(page) {
        return Some(format!("{page}: path-escapes"));
    }
    let content = match fs::read(papers.join(page)) {
        Ok(content) => content,
        Err(_) => return Some(format!("{page}: quote-not-found")),
    };
    let stored = collapse(&String::from_utf8_lossy(&content));
    if stored.contains(&collapse(text)) {
        None
    } else {
        Some(format!("{page}: quote-not-found"))
    }
}

/// Whether a catalog or note path leaves the papers directory: an absolute
/// path or one with a `..` segment. Merge workers write these paths, so the
/// validator never follows one out of the directory it checks.
fn escapes(path: &str) -> bool {
    let path = Path::new(path);
    path.is_absolute() || path.components().any(|c| c == Component::ParentDir)
}

/// Problems of the entries' own files and quotes: `file-not-found` and
/// `quote-not-found`, in catalog order.
fn file_problems(papers: &Path, entries: &[Entry]) -> Vec<String> {
    let mut problems = Vec::new();
    for e in entries {
        for file in &e.files {
            if escapes(file) {
                problems.push(format!("{file}: path-escapes"));
            } else if !papers.join(file).exists() {
                problems.push(format!("{file}: file-not-found"));
            }
        }
        for q in e.quotes.iter().flatten() {
            if let Some(problem) = quote_problem(papers, &q.text, &q.page) {
                problems.push(problem);
            }
        }
    }
    problems
}

/// How far `tier` sits below A; an unknown tier defaults to B's rank.
fn tier_rank(tier: &str) -> usize {
    TIERS.iter().position(|t| *t == tier).unwrap_or(1)
}

/// The entries grouped by theme, theme names sorted.
fn groups(entries: &[Entry]) -> BTreeMap<&str, Vec<&Entry>> {
    let mut groups: BTreeMap<&str, Vec<&Entry>> = BTreeMap::new();
    for e in entries {
        groups.entry(e.theme.as_str()).or_default().push(e);
    }
    groups
}

/// Every theme named by an entry, sorted.
fn all_themes(entries: &[Entry]) -> BTreeSet<&str> {
    entries.iter().map(|e| e.theme.as_str()).collect()
}

/// One theme's entries sorted by year (absent year counts as 0) then title.
fn by_year_title<'a>(entries: &'a [&'a Entry]) -> Vec<&'a Entry> {
    let mut entries = entries.to_vec();
    entries.sort_by(|a, b| (a.year.unwrap_or(0), &a.title).cmp(&(b.year.unwrap_or(0), &b.title)));
    entries
}

/// The `(year, tier)` half of an index line.
fn year_tier(e: &Entry) -> String {
    match e.year {
        Some(y) => format!("({y}, tier {})", e.tier),
        None => format!("(tier {})", e.tier),
    }
}

/// The top-level `INDEX.md`: every theme with its entry count, then every
/// entry (title, year, tier, theme link).
fn top_index(entries: &[Entry]) -> String {
    if entries.is_empty() {
        return format!("{MARKER}\n# Papers\n\nNo entries yet.\n");
    }
    let mut themes = String::new();
    let mut list = String::new();
    for (theme, es) in groups(entries) {
        let n = es.len();
        let word = if n == 1 { "entry" } else { "entries" };
        themes.push_str(&format!("- [{theme}]({theme}) ({n} {word})\n"));
        for e in by_year_title(&es) {
            list.push_str(&format!(
                "- **{}** {} — [{theme}]({theme})\n",
                e.title,
                year_tier(e)
            ));
        }
    }
    format!("{MARKER}\n# Papers\n\n## Themes\n\n{themes}\n## Entries\n\n{list}")
}

/// One theme's `INDEX.md`: its entries sorted by year then title, with the
/// summary when present.
fn theme_index(theme: &str, entries: &[&Entry]) -> String {
    let mut list = String::new();
    for e in by_year_title(entries) {
        list.push_str(&format!("- **{}** {}", e.title, year_tier(e)));
        if let Some(summary) = &e.summary {
            list.push_str(&format!(": {summary}"));
        }
        list.push('\n');
    }
    format!("{MARKER}\n# {theme}\n\n{list}")
}

/// Every `INDEX.md` that differs from what `index` would generate.
fn stale_problems(papers: &Path, entries: &[Entry]) -> Vec<String> {
    let mut problems = Vec::new();
    if fs::read_to_string(papers.join("INDEX.md")).unwrap_or_default() != top_index(entries) {
        problems.push("INDEX.md: stale-index".to_string());
    }
    for (theme, es) in groups(entries) {
        let name = format!("{theme}/INDEX.md");
        if fs::read_to_string(papers.join(&name)).unwrap_or_default() != theme_index(theme, &es) {
            problems.push(format!("{name}: stale-index"));
        }
    }
    problems
}

/// The theme folders without a hand-written `README.md` explainer.
fn theme_problems(papers: &Path, entries: &[Entry]) -> Vec<String> {
    let mut problems = Vec::new();
    for theme in all_themes(entries) {
        if !papers.join(theme).join("README.md").exists() {
            problems.push(format!("{theme}: missing-theme-readme"));
        }
    }
    problems
}

/// Collects the paths of every regular file under `dir`, recursively, each
/// prefixed with `prefix` (the papers-relative path of `dir`).
fn walk_files(dir: &Path, prefix: &str, out: &mut Vec<String>) {
    let Ok(read) = fs::read_dir(dir) else {
        return;
    };
    let mut found: Vec<_> = read.flatten().collect();
    found.sort_by_key(|e| e.file_name());
    for e in found {
        let path = e.path();
        let name = e.file_name().to_string_lossy().into_owned();
        let rel = format!("{prefix}/{name}");
        if path.is_dir() {
            walk_files(&path, &rel, out);
        } else {
            out.push(rel);
        }
    }
}

/// Whether a file under a theme folder is allowed without being listed: the
/// explainer `README.md`, a generated `INDEX.md`, or anything inside a
/// `<name>-images/` folder of a listed file.
fn extra_allowed(rel: &str, image_dirs: &BTreeSet<String>) -> bool {
    let file = rel.rsplit('/').next().unwrap_or("");
    if file == "README.md" || file == "INDEX.md" {
        return true;
    }
    rel.split('/')
        .any(|part| image_dirs.contains(&part.to_string()))
}

/// Files under the theme folders that no catalog entry lists.
fn unlisted_problems(papers: &Path, entries: &[Entry]) -> Vec<String> {
    let listed: BTreeSet<&str> = entries
        .iter()
        .flat_map(|e| e.files.iter().map(String::as_str))
        .collect();
    let mut image_dirs: BTreeSet<String> = BTreeSet::new();
    for file in &listed {
        if let Some(stem) = Path::new(file).file_stem() {
            image_dirs.insert(format!("{}-images", stem.to_string_lossy()));
        }
    }
    let mut problems = Vec::new();
    let groups: BTreeSet<&str> = all_themes(entries)
        .into_iter()
        .map(|theme| theme.split('/').next().unwrap_or(theme))
        .collect();
    for group in groups {
        let mut found = Vec::new();
        walk_files(&papers.join(group), group, &mut found);
        for rel in found {
            if !listed.contains(rel.as_str()) && !extra_allowed(&rel, &image_dirs) {
                problems.push(format!("{rel}: unlisted-file"));
            }
        }
    }
    problems
}

/// Top-level files or folders that are neither allowed names nor a theme
/// group used by the catalog.
fn top_level_problems(papers: &Path, entries: &[Entry]) -> Vec<String> {
    let mut theme_groups: BTreeSet<&str> = BTreeSet::new();
    for e in entries {
        theme_groups.insert(e.theme.split('/').next().unwrap_or_default());
    }
    let mut names = Vec::new();
    if let Ok(read) = fs::read_dir(papers) {
        names.extend(
            read.flatten()
                .map(|e| e.file_name().to_string_lossy().into_owned()),
        );
    }
    names.sort();
    let mut problems = Vec::new();
    for name in names {
        let allowed = if papers.join(&name).is_dir() {
            ALLOWED_DIRS.contains(&name.as_str()) || theme_groups.contains(name.as_str())
        } else {
            ALLOWED_FILES.contains(&name.as_str())
        };
        if !allowed {
            problems.push(format!("{name}: not-allowed"));
        }
    }
    problems
}

/// The `*.md` files directly in `notes/` other than its `README.md`, sorted.
fn note_names(papers: &Path) -> Vec<String> {
    let mut names = Vec::new();
    if let Ok(read) = fs::read_dir(papers.join("notes")) {
        for e in read.flatten() {
            let path = e.path();
            if path.extension().is_some_and(|x| x == "md") && e.file_name() != "README.md" {
                names.push(e.file_name().to_string_lossy().into_owned());
            }
        }
    }
    names.sort();
    names
}

/// A note's YAML-like front matter (between `---` lines) and its body; an
/// unclosed front matter runs to the end of the file.
fn split_front(text: &str) -> (Vec<&str>, Vec<&str>) {
    let lines: Vec<&str> = text.lines().collect();
    if lines.first() != Some(&"---") {
        return (Vec::new(), lines);
    }
    let end = lines
        .iter()
        .skip(1)
        .position(|l| *l == "---")
        .map(|i| i + 1)
        .unwrap_or(lines.len());
    (
        lines[1..end].to_vec(),
        lines[(end + 1).min(lines.len())..].to_vec(),
    )
}

/// The note's `min_tier`, defaulting to B; an unknown value also means B.
fn min_rank(front: &[&str]) -> usize {
    for line in front {
        if let Some(value) = line.strip_prefix("min_tier: ") {
            return tier_rank(value.trim());
        }
    }
    1
}

/// The ids of the note's one-line `cites: [id1, id2]` list.
fn cites(front: &[&str]) -> Vec<String> {
    for line in front {
        if let Some(list) = line.strip_prefix("cites: ") {
            let inner = list.trim().trim_start_matches('[').trim_end_matches(']');
            return inner
                .split(',')
                .map(str::trim)
                .filter(|id| !id.is_empty())
                .map(str::to_string)
                .collect();
        }
    }
    Vec::new()
}

/// Problems of the notes: `unknown-cite`, `tier-below-min` and the quotes'
/// `quote-not-found`, note by note.
fn note_problems(papers: &Path, entries: &[Entry]) -> Vec<String> {
    let tiers: BTreeMap<&str, &str> = entries
        .iter()
        .map(|e| (e.id.as_str(), e.tier.as_str()))
        .collect();
    let mut problems = Vec::new();
    for name in note_names(papers) {
        let note = format!("notes/{name}");
        let text = fs::read_to_string(papers.join(&note)).unwrap_or_default();
        let (front, body) = split_front(&text);
        let min = min_rank(&front);
        for id in cites(&front) {
            match tiers.get(id.as_str()) {
                None => problems.push(format!("{note}: unknown-cite")),
                Some(tier) => {
                    if tier_rank(tier) > min {
                        problems.push(format!("{note}: tier-below-min"));
                    }
                }
            }
        }
        let mut pending: Option<String> = None;
        for line in body {
            if let Some(quote) = line.strip_prefix("> ") {
                pending = match pending.take() {
                    None => Some(quote.trim().to_string()),
                    Some(mut joined) => {
                        joined.push(' ');
                        joined.push_str(quote.trim());
                        Some(joined)
                    }
                };
            } else if let Some(page) = line.strip_prefix("-- ") {
                if let Some(quote) = pending.take() {
                    if let Some(problem) = quote_problem(papers, &quote, page.trim()) {
                        problems.push(problem);
                    }
                }
            } else if !line.trim().is_empty() {
                pending = None;
            }
        }
    }
    problems
}

/// The rule of one broken catalog entry: `missing-field: <name>` when serde
/// names a missing field, the serde error otherwise.
fn entry_problem(err: serde_json::Error) -> String {
    let message = err.to_string();
    if let Some(field) = message
        .strip_prefix("missing field `")
        .and_then(|rest| rest.split('`').next())
    {
        format!("missing-field: {field}")
    } else {
        format!("bad-catalog-entry: {message}")
    }
}

/// Reads `catalog.json`: a fatal problem (unreadable, not JSON, not an
/// array) as `Err`, otherwise the well-formed entries plus one problem per
/// broken entry or bad tier.
fn read_catalog(papers: &Path) -> Result<(Vec<Entry>, Vec<String>), String> {
    let text = fs::read_to_string(papers.join(CATALOG))
        .map_err(|e| format!("{CATALOG}: cannot read: {e}"))?;
    let value: Value =
        serde_json::from_str(&text).map_err(|e| format!("{CATALOG}: not valid JSON: {e}"))?;
    let array = value
        .as_array()
        .ok_or_else(|| format!("{CATALOG}: not an array"))?;
    let mut entries = Vec::new();
    let mut problems = Vec::new();
    for item in array {
        let id = item
            .get("id")
            .and_then(Value::as_str)
            .unwrap_or(CATALOG)
            .to_string();
        match serde_json::from_value::<Entry>(item.clone()) {
            Ok(e) => {
                if TIERS.contains(&e.tier.as_str()) {
                    entries.push(e);
                } else {
                    problems.push(format!("{id}: bad-tier"));
                }
            }
            Err(err) => problems.push(format!("{id}: {}", entry_problem(err))),
        }
    }
    Ok((entries, problems))
}

/// Every problem a papers directory has, in a stable order.
pub fn check(papers: &Path) -> Vec<String> {
    let (entries, mut problems) = match read_catalog(papers) {
        Ok(found) => found,
        Err(problem) => return vec![problem],
    };
    problems.extend(file_problems(papers, &entries));
    problems.extend(theme_problems(papers, &entries));
    problems.extend(stale_problems(papers, &entries));
    problems.extend(unlisted_problems(papers, &entries));
    problems.extend(top_level_problems(papers, &entries));
    problems.extend(note_problems(papers, &entries));
    problems
}

/// Writes one generated index, recording a failure instead of panicking.
/// Failures name the index by its papers-relative path, as documented.
fn write_one(dir: &Path, name: &str, shown: &str, text: &str, failures: &mut Vec<String>) {
    if let Err(e) = fs::create_dir_all(dir) {
        failures.push(format!("{shown}: cannot create: {e}"));
        return;
    }
    if let Err(e) = fs::write(dir.join(name), text) {
        failures.push(format!("{shown}: cannot write: {e}"));
    }
}

/// Rewrites every `INDEX.md` of the papers directory: the top-level one and
/// each theme's. Fails with the catalog problems, or a write failure.
pub fn write_indexes(papers: &Path) -> Result<usize, Vec<String>> {
    let (entries, problems) = match read_catalog(papers) {
        Ok(found) => found,
        Err(problem) => return Err(vec![problem]),
    };
    if !problems.is_empty() {
        return Err(problems);
    }
    let mut failures = Vec::new();
    write_one(
        papers,
        "INDEX.md",
        "INDEX.md",
        &top_index(&entries),
        &mut failures,
    );
    let mut count = 1;
    for (theme, es) in groups(&entries) {
        write_one(
            &papers.join(theme),
            "INDEX.md",
            &format!("{theme}/INDEX.md"),
            &theme_index(theme, &es),
            &mut failures,
        );
        count += 1;
    }
    if failures.is_empty() {
        Ok(count)
    } else {
        Err(failures)
    }
}

/// The outside world `mount` talks to: GitHub visibility and git. Tests use
/// a fake; only [GhGit], the real impl, touches processes.
trait Outside {
    fn visibility(&mut self, url: &str) -> Result<String, String>;
    fn git(&mut self, repo: &Path, args: &[&str]) -> Result<String, String>;
}

/// Adds the papers repository as a git submodule at `research/`. Idempotent
/// when the submodule already carries `url`; refuses a non-GitHub url, a
/// remote whose visibility cannot be checked, and a public remote.
fn mount(outside: &mut dyn Outside, repo: &Path, url: &str) -> Result<String, String> {
    if let Ok(current) = outside.git(
        repo,
        &[
            "config",
            "-f",
            ".gitmodules",
            "--get",
            "submodule.research.url",
        ],
    ) {
        if current.trim() == url {
            return Ok("research/ already mounted".to_string());
        }
    }
    github_slug(url).ok_or_else(|| format!("{url}: not-a-github-url"))?;
    let visibility = outside
        .visibility(url)
        .map_err(|e| format!("{url}: cannot check visibility: {e}"))?;
    if visibility.trim() == "public" {
        return Err(format!("{url}: public-remote"));
    }
    outside
        .git(repo, &["submodule", "add", url, "research"])
        .map_err(|e| format!("research/: cannot add submodule: {e}"))?;
    Ok("research/ mounted".to_string())
}

/// The `owner/name` of an https or ssh GitHub URL, or `None` for anything
/// else (unverifiable).
fn github_slug(url: &str) -> Option<String> {
    let path = [
        "https://github.com/",
        "git@github.com:",
        "ssh://git@github.com/",
    ]
    .iter()
    .find_map(|prefix| url.strip_prefix(prefix))?;
    let path = path.trim_end_matches('/').trim_end_matches(".git");
    let (owner, name) = path.split_once('/')?;
    if owner.is_empty() || name.is_empty() || name.contains('/') {
        return None;
    }
    Some(format!("{owner}/{name}"))
}

/// The real outside world: `gh` and `git` subprocesses.
///
/// This impl, its unit struct and the `run_out` helper below are the ONLY
/// untested code in this crate — every test mounts through the fake
/// [Outside] — so by the workspace standard they stay these few lines.
struct GhGit;

impl Outside for GhGit {
    fn visibility(&mut self, url: &str) -> Result<String, String> {
        let slug = github_slug(url).ok_or_else(|| "not a GitHub URL".to_string())?;
        let out = std::process::Command::new("gh")
            .arg("repo")
            .arg("view")
            .arg(&slug)
            .arg("--json")
            .arg("visibility")
            .arg("--jq")
            .arg(".visibility")
            .output()
            .map_err(|e| e.to_string())?;
        run_out(&out)
    }

    fn git(&mut self, repo: &Path, args: &[&str]) -> Result<String, String> {
        let out = std::process::Command::new("git")
            .arg("-C")
            .arg(repo)
            .args(args)
            .output()
            .map_err(|e| e.to_string())?;
        run_out(&out)
    }
}

fn run_out(out: &std::process::Output) -> Result<String, String> {
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
    } else {
        Err(String::from_utf8_lossy(&out.stderr).trim().to_string())
    }
}

/// The usage text a bad command line prints on stderr.
fn usage() {
    eprintln!("usage: {NAME} check <PAPERS_DIR>");
    eprintln!("       {NAME} index <PAPERS_DIR>");
    eprintln!("       {NAME} mount <REPO_ROOT> <REMOTE_URL>");
}

/// Prints the problems (each `research-layout: <path>: <rule>`) and returns 1,
/// or prints `ok` and returns 0.
fn report(problems: &[String]) -> i32 {
    if problems.is_empty() {
        println!("{NAME}: ok");
        return 0;
    }
    for problem in problems {
        eprintln!("{NAME}: {problem}");
    }
    1
}

/// The `check` command line.
fn check_command(dir: Option<OsString>) -> i32 {
    let Some(dir) = dir else {
        usage();
        return 2;
    };
    report(&check(Path::new(&dir)))
}

/// The `index` command line.
fn index_command(dir: Option<OsString>) -> i32 {
    let Some(dir) = dir else {
        usage();
        return 2;
    };
    match write_indexes(Path::new(&dir)) {
        Ok(count) => {
            println!("{NAME}: {count} indexes regenerated");
            0
        }
        Err(problems) => report(&problems),
    }
}

/// The `mount` command line, wired to the real outside world (untested, see
/// [GhGit]); `mount` itself, above, is fully tested through the fake.
fn real_mount(repo: &Path, url: &str) -> i32 {
    match mount(&mut GhGit, repo, url) {
        Ok(message) => {
            println!("{NAME}: {message}");
            0
        }
        Err(problem) => {
            eprintln!("{NAME}: {problem}");
            1
        }
    }
}

/// Runs one command line and returns its exit code: 0 ok, 1 a rule failed,
/// 2 bad usage. Success prints to stdout, problems to stderr.
pub fn run<I>(args: I) -> i32
where
    I: IntoIterator<Item = OsString>,
{
    let mut args = args.into_iter();
    let (cmd, one, two) = (args.next(), args.next(), args.next());
    if args.next().is_some() {
        usage();
        return 2;
    }
    match cmd.as_deref() {
        Some(c) if c == OsStr::new("check") && two.is_none() => check_command(one),
        Some(c) if c == OsStr::new("index") && two.is_none() => index_command(one),
        Some(c) if c == OsStr::new("mount") => match (one, two) {
            (Some(repo), Some(url)) => real_mount(Path::new(&repo), &url.to_string_lossy()),
            _ => {
                usage();
                2
            }
        },
        _ => {
            usage();
            2
        }
    }
}

