import { chmod } from 'node:fs/promises'
import { resolve } from 'node:path'

import { build as esbuild } from 'esbuild'

const packageRoot = resolve(import.meta.dirname, '..')
const councilRoot = resolve(packageRoot, '..')
const critiqueRunnerPath = resolve(councilRoot, '..', 'skills', 'workstation', 'critique', 'critique.mjs')
const buildTrackerRunnerPath = resolve(councilRoot, '..', 'skills', 'workstation', 'build-tracker', 'build-tracker.mjs')
const modelGatewayRunnerPath = resolve(councilRoot, '..', 'skills', 'workstation', 'model-gateway', 'model-gateway.mjs')

await bundleCritiqueRunner()
await bundleBuildTrackerRunner()
await bundleModelGatewayRunner()

// A skill's runner: one self-contained, executable ES module bundled from an
// entry written here, with no runtime dependencies beyond Node's own modules.
// `source` is the folder under council/ts/src the banner names.
async function bundleRunner({ outfile, source, entryName, entry }) {
  await esbuild({
    banner: {
      js: `#!/usr/bin/env node\n// Generated by council/ts/scripts/build.mjs from council/ts/src/${source}. Do not edit.`,
    },
    bundle: true,
    format: 'esm',
    legalComments: 'none',
    logLevel: 'warning',
    outfile,
    platform: 'node',
    stdin: {
      contents: entry,
      loader: 'ts',
      resolveDir: packageRoot,
      sourcefile: entryName,
    },
    target: 'node22',
  })
  await chmod(outfile, 0o755)
}

// The build tracker's runner ships in the build-tracker skill directory as one
// self-contained file, the way the critique runner does.
async function bundleBuildTrackerRunner() {
  await bundleRunner({
    entry: `import { defaultBuildTrackerRuntime, runBuildTrackerCli } from './src/build-tracker-cli/index.ts'

const result = await runBuildTrackerCli(process.argv.slice(2), defaultBuildTrackerRuntime())
process.stderr.write(result.stderr, () => {
  process.stdout.write(result.stdout, () => process.exit(result.exitCode))
})
`,
    entryName: 'build-tracker-runner-entry.ts',
    outfile: buildTrackerRunnerPath,
    source: 'build-tracker-cli',
  })
}

