import { join } from 'node:path'

import { afterEach, describe, expect, it } from 'vitest'

import { fenced, harness, isolatedExport, vibeStdout, writeFlowState, type Harness } from '../../../test/critique/harness.js'
import type { GateResult } from './index.js'

/**
 * The commit gate on merge commits (#260). A clean `git merge` commits
 * without any `git commit`, and a merge that stopped on a conflict is
 * concluded by a `git commit` while `MERGE_HEAD` is set. The gate lets
 * either through when every commit the merge brings in passed a ticket
 * review that was not degraded, or was low-risk on its own, and the merge
 * adds nothing beyond those commits but manifest pins and rebuilt generated
 * files. Anything else is judged like any staged change.
 */

const open: Harness[] = []

afterEach(async () => {
  await Promise.all(open.splice(0).map((h) => h.cleanup()))
})

const SPEC = '.scratch/widgets/spec.md'
const TICKET = '.scratch/widgets/issues/01-session.md'
const RISKY_PATH = 'src/auth/session.ts'
const BUNDLE = 'skills/critique/critique.mjs'
const pin = (digit: string) => `    sha256: ${digit.repeat(64)}\n`
const manifest = (bundlePin: string, extra = '') => `critique:\n  files:\n    - path: ${BUNDLE}\n${bundlePin}${extra}`
const bundle = (build: string) => `#!/usr/bin/env node\n// Generated by council/ts/scripts/build.mjs. Do not edit.\nexport const build = '${build}'\n`

/** A repository opted in for code, with its ticket, a widget, a pinned generated bundle and its manifest committed on main. */
async function optedIn(options: Parameters<typeof harness>[0] = {}): Promise<Harness> {
  const h = await harness(options)
  open.push(h)
  await writeFlowState(h)
  await h.commands.allow.run({ code: true, families: ['mistral', 'zhipu'], repo: h.repo })
  await h.writeText(join(h.repo, TICKET), '# 01: Sessions expire\n\n## Acceptance criteria\n\n- [ ] A session expires after a minute.\n')
  await h.writeText(join(h.repo, 'src/widget.ts'), 'export const widgets = 1\n')
  await h.writeText(join(h.repo, BUNDLE), bundle('base'))
  await h.writeText(join(h.repo, 'manifest.yaml'), manifest(pin('0')))
  await h.git.commit()
  return h
}

function gate(h: Harness, command: string): Promise<GateResult> {
  return h.commands.gate.run({ cwd: h.repo, hook_event_name: 'PreToolUse', tool_input: { command }, tool_name: 'Bash' })
}

function deny(line: string): unknown {
  return { hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: line } }
}

/** Runs `/review-implementation` on the staged change as the skill does, with a critic that finds nothing, so the review passes. */
async function reviewStaged(h: Harness): Promise<void> {
  h.process.queue({ exitCode: 0, exportJson: isolatedExport(), stdout: vibeStdout(fenced({ findings: [], no_findings_reason: 'Read the diff.' })) })
  const run = await h.commands.prepare.run({
    base: 'HEAD',
    orchestrator_family: 'anthropic',
    repo: h.repo,
    spec: SPEC,
    stage: 'ticket-review',
    staged: true,
    ticket: TICKET,
  })
  if (run.status !== 'ready') throw new Error(`prepare refused: ${run.message}`)
  await h.commands.fanOut.run({ run_dir: run.run_dir })
  await h.commands.record.run({ run_dir: run.run_dir, verdicts: [] })
}

/**
 * Makes branch `feat` off main with one commit to the risk path, reviewed
 * by /review-implementation before it was committed when `reviewed`, then goes back
 * to main. `files` adds more files to that commit.
 */
async function featureBranch(h: Harness, options: { readonly reviewed: boolean; readonly files?: Readonly<Record<string, string>> }): Promise<string> {
  await h.git.checkout('feat', 'HEAD')
  await h.writeText(join(h.repo, RISKY_PATH), 'export const ttl = 60\n')
  for (const [path, text] of Object.entries(options.files ?? {})) await h.writeText(join(h.repo, path), text)
  await h.git.stage()
  if (options.reviewed) await reviewStaged(h)
  const commit = await h.git.commit()
  await h.git.checkout('main')
  return commit
}

/** Rewrites the last line of the ticket-review index with `changes`, as a later review of the same change would leave it. */
async function rewriteLastReview(h: Harness, changes: Record<string, unknown>): Promise<void> {
  const index = join(h.repo, '.git', 'critique', 'ticket-reviews.jsonl')
  const lines = (await h.readText(index)).trim().split('\n')
  const last = JSON.stringify({ ...(JSON.parse(lines.at(-1) ?? '{}') as object), ...changes })
  await h.writeText(index, `${[...lines.slice(0, -1), last].join('\n')}\n`)
}

/** Commits files on the current branch, unreviewed. */
async function commitFiles(h: Harness, files: Readonly<Record<string, string>>): Promise<string> {
  for (const [path, text] of Object.entries(files)) await h.writeText(join(h.repo, path), text)
  return h.git.commit()
}

describe('a merge that `git merge` commits', () => {
  it('is judged when it brings in a commit no review passed, and blocked when risky', async () => {
    const h = await optedIn()
    const commit = await featureBranch(h, { reviewed: false })

    const line = `Merge blocked: merging feat is risky (src/auth/session.ts is a risk path) and ${commit}, a commit it brings in, has no passing /review-implementation run. Stage the merge with git merge --no-commit feat, run /review-implementation, then commit.`
    expect(await gate(h, 'git merge --no-ff feat')).toEqual({ gate: 'commit', hook_output: deny(line), line, reason: 'unreviewed', status: 'blocked' })
  })

  it('is allowed when every commit it brings in passed /review-implementation', async () => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: true })

    expect(await gate(h, 'git merge --no-ff feat')).toEqual({ gate: 'commit', line: null, reason: 'merge-vouched', status: 'allowed' })
  })

  it.each([
    ['degraded', { degraded: true, review: 'degraded' }],
    ['degraded, as a record written before #259 says', { degraded: true, review: 'pass' }],
    ['failed', { review: 'fail', unfixed_critical: ['F1'] }],
  ])('is judged when the review of a commit it brings in %s', async (_name, changes) => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: true })
    await rewriteLastReview(h, changes)

    expect(await gate(h, 'git merge --no-ff feat')).toMatchObject({ reason: 'unreviewed', status: 'blocked' })
  })

  it('counts a commit the commit gate let through alone, low-risk, as vouched for', async () => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: true })
    await h.git.checkout('feat')
    await commitFiles(h, { 'src/widget.ts': 'export const widgets = 3\n' })
    await h.git.checkout('main')

    expect(await gate(h, 'git merge --no-ff feat')).toMatchObject({ reason: 'merge-vouched' })
  })

  it("reads a low-risk commit's risk:high label from the triage of the change it was made from", async () => {
    const h = await optedIn()
    const head = await h.git.resolveCommit('', 'HEAD')
    await h.git.checkout('feat', 'HEAD')
    const commit = await commitFiles(h, { 'src/widget.ts': 'export const widgets = 3\n' })
    await h.git.checkout('main')
    const triage = { labels: ['risk:high'], recorded_at: '2026-10-30T12:00:00.000Z', repository: 'github.com/jorisjonkers-dev/agent-kit' }
    const line = { ...triage, run_id: 'r1', staged_diff: 'x', staged_on: head, status: 'risky', ticket: 'x', version: 1 }
    await h.writeText(join(h.repo, '.git', 'critique', 'triages.jsonl'), `${JSON.stringify(line)}\n`)

    expect(await gate(h, 'git merge --no-ff feat')).toMatchObject({
      line: `Merge blocked: merging feat is risky (the ticket carries risk:high) and ${commit}, a commit it brings in, has no passing /review-implementation run. Stage the merge with git merge --no-commit feat, run /review-implementation, then commit.`,
    })
  })

  it('judges the merge on what it changes against HEAD, so an unreviewed commit main already holds is low-risk', async () => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: false })
    await commitFiles(h, { [RISKY_PATH]: 'export const ttl = 60\n' })

    expect(await gate(h, 'git merge feat')).toMatchObject({ reason: 'low-risk', status: 'allowed' })
  })

  it('is left to the commit that concludes it when it conflicts, since git stops before committing', async () => {
    const h = await optedIn()
    await featureBranch(h, { files: { 'src/widget.ts': 'export const widgets = 2\n' }, reviewed: false })
    await commitFiles(h, { 'src/widget.ts': 'export const widgets = 3\n' })

    expect(await gate(h, 'git merge feat')).toMatchObject({ reason: 'merge-stops', status: 'allowed' })
  })

  it('is not gated when git fast-forwards, or the branch is merged already', async () => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: false })

    expect(await gate(h, 'git merge feat')).toEqual({ gate: 'commit', line: null, reason: 'not-gated', status: 'allowed' })
    expect(await gate(h, 'git merge --ff main')).toMatchObject({ reason: 'not-gated' })
  })

  it('still judges `git merge -n`, since -n is --no-stat and the merge commits', async () => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: false })
    await commitFiles(h, { 'docs/notes.md': 'Notes.\n' })

    expect(await gate(h, 'git merge -n --no-ff feat')).toMatchObject({ reason: 'unreviewed', status: 'blocked' })
  })

  it.each([
    ['git merge --ff-only feat'],
    ['git merge --squash feat'],
    ['git merge --no-commit --no-ff feat'],
    ['git merge --abort'],
    ['git merge --quit'],
    ['git pull --rebase origin feat'],
    ['git pull --rebase=merges origin feat'],
    ['git pull -r origin feat'],
    ['git pull --ff-only'],
  ])('is not gated for %s, which records no merge commit', async (command) => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: false })
    h.git.setBranch('origin/feat', 'feat')

    expect(await gate(h, command)).toEqual({ gate: null, line: null, reason: 'not-gated', status: 'allowed' })
  })

  it.each([
    ['git merge -m "Merge feat" --no-ff feat', 'feat'],
    ['git merge --no-ff --strategy ort -X theirs feat', 'feat'],
    ['git merge --no-ff -nm msg -- feat', 'feat'],
    ['git merge --squash --commit --no-ff feat', 'feat'],
    ['git merge --no-ff', '@{upstream}'],
    ['git pull --no-ff --depth 1 origin feat', 'origin/feat'],
    ['git pull --rebase=false --no-ff origin +refs/heads/feat:feat', 'origin/feat'],
    ['git pull --rebase --no-rebase -j 2 --no-ff', '@{upstream}'],
    // Git merges the branch's configured upstream here, and refuses when it is on another remote.
    ['git pull --no-ff origin', '@{upstream}'],
  ])('reads what %s merges', async (command, revision) => {
    const h = await optedIn()
    const commit = await featureBranch(h, { reviewed: false })
    h.git.setBranch(revision, commit)

    expect((await gate(h, command)).line).toContain(`merging ${revision} is risky`)
  })

  it.each([['git checkout feat && git merge --no-ff main'], ['git switch feat; git merge main'], ['git commit -m x && git pull origin main']])(
    'is blocked when %s moves HEAD before it merges, since what the merge brings in is not known yet',
    async (command) => {
      const h = await optedIn()
      await featureBranch(h, { reviewed: true })
      await commitFiles(h, { [RISKY_PATH]: 'export const ttl = 1\n' })

      const line = 'Merge blocked: this command moves HEAD before it merges, so the gate cannot tell what the merge brings in. Run the merge in a command of its own.'
      expect(await gate(h, command)).toEqual({ gate: 'commit', hook_output: deny(line), line, reason: 'head-unknown', status: 'blocked' })
    },
  )

  it('judges each branch of an octopus merge, which never fast-forwards', async () => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: true })
    await h.git.checkout('docs', 'main')
    await commitFiles(h, { 'docs/notes.md': 'Notes.\n' })
    await h.git.checkout('main')

    expect(await gate(h, 'git merge feat docs')).toMatchObject({ reason: 'merge-vouched' })
  })

  it('fails open when routing has no triage, so there are no risk rules', async () => {
    const h = await optedIn({ routingOverride: { triage: null } })
    await featureBranch(h, { reviewed: false })

    expect(await gate(h, 'git merge --no-ff feat')).toMatchObject({
      detail: 'routing has no triage, so the commit gate has no risk rules',
      reason: 'failed-open',
    })
  })

  it('fails open when what it merges names no commit', async () => {
    const h = await optedIn()

    expect(await gate(h, 'git merge nope')).toMatchObject({ gate: 'commit', reason: 'failed-open', status: 'allowed' })
  })
})

/**
 * The feature branch's reviewed commit also rebuilds the bundle and its
 * pin, main rebuilds them meanwhile, and `git merge feat` stopped on the
 * conflicts in both; they are resolved as a rebuild does, and staged.
 */
async function rebuildConflict(h: Harness): Promise<void> {
  await featureBranch(h, { files: { [BUNDLE]: bundle('feat'), 'manifest.yaml': manifest(pin('1')) }, reviewed: true })
  await commitFiles(h, { [BUNDLE]: bundle('main'), 'manifest.yaml': manifest(pin('2')) })
  await h.git.merge('feat')
  await h.writeText(join(h.repo, BUNDLE), bundle('merged'))
  await h.writeText(join(h.repo, 'manifest.yaml'), manifest(pin('3')))
  await h.git.stage()
}

describe('a merge that a `git commit` concludes', () => {
  it('is allowed when its commits passed review and it resolved conflicts only in manifest pins and a rebuilt generated file', async () => {
    const h = await optedIn()
    await rebuildConflict(h)

    expect(await gate(h, 'git commit --no-edit')).toEqual({ gate: 'commit', line: null, reason: 'merge-vouched', status: 'allowed' })
    expect(await gate(h, 'git merge --continue')).toMatchObject({ reason: 'merge-vouched' })
  })

  it('is judged on a hand edit to a source file beyond the reviewed commits, and blocked when that edit is risky', async () => {
    const h = await optedIn()
    await rebuildConflict(h)
    await h.writeText(join(h.repo, 'src/auth/extra.ts'), 'export const extra = 1\n')
    await h.git.stage()

    const line =
      "Commit blocked: this merge's own changes beyond the reviewed commits it brings in are risky (src/auth/extra.ts is a risk path) and no passing /review-implementation run matches the staged merge. Run /review-implementation, then commit."
    expect(await gate(h, 'git commit --no-edit')).toEqual({ gate: 'commit', hook_output: deny(line), line, reason: 'unreviewed', status: 'blocked' })
  })

  it('judges only the hand edit, so a low-risk one passes though the merge brings in a risky change', async () => {
    const h = await optedIn()
    await rebuildConflict(h)
    await h.writeText(join(h.repo, 'src/widget.ts'), 'export const widgets = 9\n')
    await h.git.stage()

    expect(await gate(h, 'git commit --no-edit')).toMatchObject({ reason: 'low-risk', status: 'allowed' })
  })

  it('lets a passing /review-implementation run of the staged merge vouch for a risky hand edit', async () => {
    const h = await optedIn()
    await rebuildConflict(h)
    await h.writeText(join(h.repo, 'src/auth/extra.ts'), 'export const extra = 1\n')
    await h.git.stage()
    await reviewStaged(h)

    expect(await gate(h, 'git commit --no-edit')).toMatchObject({ reason: 'reviewed', status: 'allowed' })
  })

  it('counts a manifest change other than its pins as its own change', async () => {
    const h = await optedIn()
    await rebuildConflict(h)
    await h.writeText(join(h.repo, 'manifest.yaml'), manifest(pin('3'), '    - path: skills/critique/extra.md\n'))
    await h.git.stage()

    expect(await gate(h, 'git commit --no-edit')).toMatchObject({ reason: 'low-risk' })
  })

  it('counts a conflict in the manifest whose sides differ beyond their pins as its own change', async () => {
    const h = await optedIn()
    await featureBranch(h, { files: { 'manifest.yaml': manifest(pin('1'), '    - path: a.md\n') }, reviewed: true })
    await commitFiles(h, { 'manifest.yaml': manifest(pin('2'), '    - path: b.md\n') })
    await h.git.merge('feat')
    await h.writeText(join(h.repo, 'manifest.yaml'), manifest(pin('3'), '    - path: a.md\n    - path: b.md\n'))
    await h.git.stage()

    expect(await gate(h, 'git commit --no-edit')).toMatchObject({ reason: 'low-risk' })
  })

  it("counts a file routing's generated globs match as rebuilt", async () => {
    const h = await optedIn()
    await featureBranch(h, { files: { 'council/ts/dist/index.js': 'feat\n' }, reviewed: true })
    await commitFiles(h, { 'council/ts/dist/index.js': 'main\n' })
    await h.git.merge('feat')
    await h.writeText(join(h.repo, 'council/ts/dist/index.js'), 'merged\n')
    await h.git.stage()

    expect(await gate(h, 'git commit --no-edit')).toMatchObject({ reason: 'merge-vouched' })
  })

  it('is judged whole when a commit it brings in has no passing review', async () => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: false })
    await commitFiles(h, { 'src/widget.ts': 'export const widgets = 3\n' })
    await h.git.merge('feat')

    expect(await gate(h, 'git commit --no-edit')).toMatchObject({
      line: 'Commit blocked: the staged change is risky (src/auth/session.ts is a risk path) and no passing /review-implementation run matches it. Run /review-implementation, then commit.',
    })
  })

  it('is judged as an ordinary commit when the commit records more than is staged', async () => {
    const h = await optedIn()
    await rebuildConflict(h)

    expect(await gate(h, 'git commit -a --no-edit')).toMatchObject({ reason: 'unreviewed', status: 'blocked' })
  })
})

describe('a merge that brings in many commits', () => {
  // Each test builds up to 200 real commits, which takes longer than vitest's
  // 5 s default on a CI runner, so these tests get the 30 s other git-heavy
  // critique tests use.
  /** Makes branch `feat` off main with `count` low-risk commits, one line of docs each, then goes back to main and moves it on. */
  async function longBranch(h: Harness, count: number, last: Readonly<Record<string, string>> = {}): Promise<void> {
    await h.git.checkout('feat', 'HEAD')
    for (let n = 0; n < count; n += 1) await commitFiles(h, { [`docs/n${String(n)}.md`]: `Note ${String(n)}.\n` })
    await commitFiles(h, last)
    await h.git.checkout('main')
    await commitFiles(h, { 'docs/main.md': 'Main.\n' })
  }

  it('is decided within the deadline past routing’s limit, judged whole against HEAD rather than commit by commit', async () => {
    const h = await optedIn()
    await longBranch(h, 200)
    const reads = h.git.treeEntryReads

    expect(await gate(h, 'git merge feat')).toEqual({ gate: 'commit', line: null, reason: 'low-risk', status: 'allowed' })
    expect(h.git.treeEntryReads).toBe(reads)
  }, 30_000)

  it('blocks such a merge when its whole change is risky, saying how many commits it brings in', async () => {
    const h = await optedIn()
    await longBranch(h, 60, { [RISKY_PATH]: 'export const ttl = 60\n' })

    expect((await gate(h, 'git merge feat')).line).toBe(
      'Merge blocked: merging feat is risky (src/auth/session.ts is a risk path) and it brings in 61 commits, more than the 50 the gate checks one by one. Stage the merge with git merge --no-commit feat, run /review-implementation, then commit.',
    )
  }, 30_000)

  it('checks commit by commit up to the limit routing sets', async () => {
    const h = await optedIn({ routingOverride: { gate: { merge_commits: 500 } } })
    await longBranch(h, 200)

    expect(await gate(h, 'git merge feat')).toMatchObject({ reason: 'merge-vouched' })
  }, 30_000)
})

describe('a merge on the branch it brings in', () => {
  it('is vouched for when it adds nothing of its own, as merging the integration branch into a ticket branch does', async () => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: true })
    await commitFiles(h, { 'docs/notes.md': 'Notes.\n' })
    await h.git.checkout('feat')
    await h.git.merge('main')
    await h.git.commit()
    await h.git.checkout('main')
    await commitFiles(h, { 'docs/more.md': 'More.\n' })

    expect(await gate(h, 'git merge feat')).toMatchObject({ reason: 'merge-vouched' })
  })

  it('is not vouched for when it adds a change of its own', async () => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: true })
    await commitFiles(h, { 'docs/notes.md': 'Notes.\n' })
    await h.git.checkout('feat')
    await h.git.merge('main')
    await h.writeText(join(h.repo, 'src/auth/extra.ts'), 'export const extra = 1\n')
    await h.git.stage()
    const merge = await h.git.commit()
    await h.git.checkout('main')
    await commitFiles(h, { 'docs/more.md': 'More.\n' })

    expect((await gate(h, 'git merge feat')).line).toContain(`and ${merge}, a commit it brings in, has no passing /review-implementation run`)
  })

  it('does not vouch for unrelated history, which git refuses to merge, so the gate fails open', async () => {
    const h = await optedIn()
    await h.git.orphan('other')
    await commitFiles(h, { 'src/auth/other.ts': 'export const other = 1\n' })
    await h.git.checkout('main')

    expect(await gate(h, 'git merge other')).toMatchObject({ detail: 'fatal: not a valid object name ', reason: 'failed-open', status: 'allowed' })
  })
})

describe('a merge with no active flow', () => {
  it('is let through even when it brings in unreviewed risky work', async () => {
    const h = await optedIn()
    await featureBranch(h, { reviewed: false })
    await h.removeFile(join(h.repo, '.git', 'critique', 'flows', 'widgets.json'))

    expect(await gate(h, 'git merge --no-ff feat')).toEqual({ gate: 'commit', line: null, reason: 'no-active-flow', status: 'allowed' })
  })
})
